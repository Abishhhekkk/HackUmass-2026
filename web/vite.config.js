import fs from "node:fs";
import path from "node:path";
import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";

// Static hosts (Netlify): write dist/_redirects. If an API address is known at build time
// (VANTAGE_API_URL, or NGROK_DOMAIN from the repo-root .env), /api/* is forwarded to it, so the
// static site shows live missions and can take the Jetson's uploads. Only the address is read
// from .env; nothing else from it reaches the build.
function apiAddress() {
  if (process.env.VANTAGE_API_URL) return process.env.VANTAGE_API_URL;
  const envFile = path.resolve(__dirname, "..", ".env");
  if (!fs.existsSync(envFile)) return null;
  const line = fs
    .readFileSync(envFile, "utf8")
    .split(/\r?\n/)
    .find((l) => /^\s*NGROK_DOMAIN\s*=/.test(l));
  const domain = line?.split("=")[1]?.trim().replace(/^["']|["']$/g, "");
  return domain ? `https://${domain.replace(/^https?:\/\//, "").replace(/\/$/, "")}` : null;
}

function staticHostRedirects() {
  return {
    name: "vantage-static-redirects",
    apply: "build",
    closeBundle() {
      const api = apiAddress()?.replace(/\/$/, "");
      const lines = ["# Generated by vite.config.js at build time."];
      if (api) lines.push(`/api/*  ${api}/api/:splat  200`);
      lines.push("/dashboard  /#/dashboard  301", "/*  /index.html  200", "");
      fs.writeFileSync(path.resolve(__dirname, "dist", "_redirects"), lines.join("\n"));
      console.log(api ? `_redirects: /api/* -> ${api}` : "_redirects: website only (no API address)");
    },
  };
}

export default defineConfig({
  plugins: [react(), staticHostRedirects()],
  server: {
    proxy: {
      "/api": process.env.VITE_API_PROXY || "http://127.0.0.1:8000",
      "/edge-api": {
        target: process.env.VITE_EDGE_API || "http://127.0.0.1:8080",
        changeOrigin: true,
        rewrite: (path) => path.replace(/^\/edge-api/, ""),
      },
    },
  },
  build: {
    outDir: "dist",
    emptyOutDir: true,
    rollupOptions: {
      output: {
        manualChunks: {
          leaflet: ["leaflet", "react-leaflet"],
          motion: ["motion/react"],
        },
      },
    },
  },
});
